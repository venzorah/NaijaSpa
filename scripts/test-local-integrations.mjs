// Uses isolated fixtures against a LOCAL database and LOCAL app, with test keys only.
// Leaves one sandbox checkout for manual completion; all other fixtures are removed.
import { createRequire } from "node:module";
import crypto from "node:crypto";
import assert from "node:assert/strict";
import { mkdir, writeFile } from "node:fs/promises";
const require = createRequire(import.meta.url);
require("@next/env").loadEnvConfig(process.cwd());
const { PrismaClient } = require("@prisma/client");
const bcrypt = require("bcryptjs");
const base = process.env.INTEGRATION_TEST_URL || "http://127.0.0.1:3101";
assert(["localhost", "127.0.0.1", "[::1]"].includes(new URL(base).hostname), "Local app required");
assert(["localhost", "127.0.0.1", "[::1]"].includes(new URL(process.env.DATABASE_URL).hostname), "Local database required");
assert(process.env.PAYSTACK_SECRET_KEY?.startsWith("sk_test_"), "Paystack TEST key required");
const db = new PrismaClient({ log: [] });
const run = `integration-${crypto.randomBytes(6).toString("hex")}`;
const ids = (suffix) => `${run}-${suffix}`;
const userIds = [ids("customer"), ids("other"), ids("owner")];
const password = crypto.randomBytes(20).toString("hex");
let retained = false;
let passed = 0;
function report(check, details = {}) { console.log(JSON.stringify({ check, ok: true, ...details })); passed++; }
async function request(path, { cookie, method = "GET", body, headers = {} } = {}) {
  const response = await fetch(`${base}${path}`, { method, redirect: "manual", signal: AbortSignal.timeout(30000),
    headers: { ...(body ? { "Content-Type": "application/json" } : {}), ...(cookie ? { Cookie: cookie } : {}), ...headers },
    ...(body !== undefined ? { body: typeof body === "string" ? body : JSON.stringify(body) } : {}) });
  const text = await response.text();
  let data; try { data = JSON.parse(text); } catch { data = null; }
  return { status: response.status, data, response, text };
}
async function login(id, expect) {
  const result = await request("/api/auth/login", { method: "POST", body: { email: `${id}@example.com`, password, expect } });
  assert.equal(result.status, 200, `Login failed: ${result.status}`);
  const cookie = result.response.headers.get("set-cookie")?.split(";")[0];
  assert(cookie, "Session cookie missing"); return cookie;
}
async function cleanup() {
  // Every deletion is constrained to the unique IDs generated by this run.
  const bookings = { vendorId: ids("vendor") };
  const bookingIds = (await db.booking.findMany({ where: bookings, select: { id: true } })).map((b) => b.id);
  const payments = await db.payment.findMany({ where: { bookingId: { in: bookingIds } }, select: { id: true } });
  await db.refund.deleteMany({ where: { paymentId: { in: payments.map((p) => p.id) } } });
  await db.payout.deleteMany({ where: { vendorId: ids("vendor") } });
  await db.vendorEarning.deleteMany({ where: { vendorId: ids("vendor") } });
  await db.payment.deleteMany({ where: { bookingId: { in: bookingIds } } });
  await db.booking.deleteMany({ where: bookings });
  await db.timeOff.deleteMany({ where: { staffId: ids("staff") } });
  await db.availabilitySlot.deleteMany({ where: { vendorId: ids("vendor") } });
  await db.auditLog.deleteMany({ where: { actorId: { in: userIds } } });
  await db.user.deleteMany({ where: { id: { in: userIds } } });
  await db.category.deleteMany({ where: { id: ids("category") } });
}

try {
  for (const path of ["/", "/explore", "/login", "/login/vendor", "/login/admin"]) {
    let page = await request(path);
    for (let hop = 0; hop < 5 && [301, 302, 303, 307, 308].includes(page.status); hop++) {
      const target = new URL(page.response.headers.get("location"), base);
      assert.equal(target.origin, new URL(base).origin, "Unexpected external redirect");
      page = await request(target.pathname + target.search);
    }
    assert.equal(page.status, 200, `Page ${path} failed`);
  }
  report("public-pages");
  assert.equal((await request("/api/bookings")).status, 401);
  assert.equal((await request("/api/payments/init", { method: "POST", body: { bookingId: "missing" } })).status, 401);
  assert.equal((await request("/api/payments/webhook", { method: "POST", body: {} })).status, 401);
  report("unauthenticated-api-and-webhook-guards");

  const passwordHash = await bcrypt.hash(password, 12);
  for (const [i, id] of userIds.entries()) await db.user.create({ data: {
    id, email: `${id}@example.com`, name: "Integration test", passwordHash,
    role: i === 2 ? "vendor_owner" : "customer"
  } });
  await db.vendor.create({ data: {
    id: ids("vendor"), ownerId: userIds[2], slug: ids("vendor"), businessName: "Integration test fixture",
    city: "Lagos", neighbourhood: "Test", address: "Test address", applicationStatus: "approved", visibility: "public",
    privatePhone: "PRIVATE-TEST-CONTACT", payoutAccountNumber: "TEST-PRIVATE-ACCOUNT", payoutRecipientCode: "TEST-PRIVATE-RECIPIENT"
  } });
  await db.category.create({ data: { id: ids("category"), slug: ids("category"), name: "Integration test" } });
  await db.vendorStaff.create({ data: { id: ids("staff"), vendorId: ids("vendor"), name: "Test therapist" } });
  await db.service.create({ data: {
    id: ids("service"), vendorId: ids("vendor"), categoryId: ids("category"), slug: ids("service"),
    name: "Integration test treatment", basePriceKobo: 10000, durationMin: 60,
    staff: { create: { staffId: ids("staff") } }
  } });
  await db.availabilitySlot.createMany({ data: Array.from({ length: 7 }, (_, weekday) => ({
    vendorId: ids("vendor"), staffId: null, weekday, startMin: 540, endMin: 1080, bufferMin: 15
  })) });
  const customer = await login(userIds[0], "customer");
  const other = await login(userIds[1], "customer");
  const owner = await login(userIds[2], "vendor");
  report("customer-and-vendor-login-and-sessions");
  const day = new Date(Date.now() + 14 * 86400000).toISOString().slice(0, 10);
  const payload = { serviceId: ids("service"), locationType: "spa", locationDetails: "", startsAt: `${day}T10:00:00+01:00`, idempotencyKey: ids("booking-key") };
  const [a, b] = await Promise.all([
    request("/api/bookings", { method: "POST", cookie: customer, body: payload }),
    request("/api/bookings", { method: "POST", cookie: other, body: { ...payload, idempotencyKey: ids("other-key") } })
  ]);
  assert.deepEqual([a.status, b.status].sort(), [200, 409], `Concurrent reservation responses: ${a.status}/${b.status}`);
  const winner = a.status === 200 ? a : b;
  const winnerCookie = a.status === 200 ? customer : other;
  const loserCookie = a.status === 200 ? other : customer;
  const winnerPayload = a.status === 200 ? payload : { ...payload, idempotencyKey: ids("other-key") };
  const bookingId = winner.data.id;
  assert.equal(await db.booking.count({ where: { vendorId: ids("vendor") } }), 1);
  report("real-postgres-concurrent-booking-lock", { successfulReservations: 1, conflicts: 1 });
  const retry = await request("/api/bookings", { method: "POST", cookie: winnerCookie, body: winnerPayload });
  assert.equal(retry.data.id, bookingId);
  assert.equal((await request("/api/bookings", { method: "POST", cookie: loserCookie, body: winnerPayload })).status, 409);
  report("idempotency-and-cross-customer-ownership");
  const listing = await request("/api/bookings", { cookie: winnerCookie });
  assert.equal(listing.status, 200);
  for (const field of ["privatePhone", "privateWhatsapp", "payoutAccountNumber", "payoutRecipientCode"]) assert(!(field in listing.data.bookings[0].vendor), `Private field exposed: ${field}`);
  report("booking-api-private-field-filter");
  for (const status of ["confirmed", "in_progress", "completed"]) {
    const result = await request(`/api/vendor/bookings/${bookingId}`, { method: "PATCH", cookie: owner, body: { status } });
    assert([400, 409].includes(result.status), `Unpaid ${status} was allowed`);
  }
  assert.equal(await db.vendorEarning.count({ where: { vendorId: ids("vendor") } }), 0);
  assert.equal(await db.payout.count({ where: { vendorId: ids("vendor") } }), 0);
  report("unpaid-confirmation-completion-and-payout-guards");
  for (const startsAt of [`${day}T03:00:00+01:00`, "2020-01-01T10:00:00+01:00"]) {
    const result = await request("/api/bookings", { method: "POST", cookie: winnerCookie, body: { ...payload, startsAt, idempotencyKey: crypto.randomUUID() } });
    assert([400, 409].includes(result.status));
  }
  const timeOff = await db.timeOff.create({ data: { staffId: ids("staff"), startsAt: new Date(`${day}T13:00:00+01:00`), endsAt: new Date(`${day}T15:00:00+01:00`), reason: "Integration test" } });
  assert.equal((await request("/api/bookings", { method: "POST", cookie: winnerCookie, body: { ...payload, startsAt: `${day}T13:00:00+01:00`, idempotencyKey: crypto.randomUUID() } })).status, 409);
  await db.timeOff.delete({ where: { id: timeOff.id } });
  report("working-hours-past-dates-and-time-off");

  const init = await request("/api/payments/init", { method: "POST", cookie: winnerCookie, body: { bookingId } });
  assert.equal(init.status, 200, `Paystack initialization failed (${init.status})`);
  assert(init.data.authorizationUrl?.startsWith("https://checkout.paystack.com/"));
  const reference = init.data.reference;
  const pending = await request(`/api/payments/verify?reference=${encodeURIComponent(reference)}`, { cookie: winnerCookie });
  assert.equal(pending.status, 200);
  assert.notEqual(pending.data.status, "success");
  assert.equal((await db.booking.findUnique({ where: { id: bookingId } })).status, "awaiting_payment");
  assert.equal((await request(`/api/payments/verify?reference=${encodeURIComponent(reference)}`, { cookie: loserCookie })).status, 403);
  report("paystack-real-test-checkout-init-and-unpaid-verification", { paymentStatus: pending.data.status });

  // Test signed delivery on a separate synthetic payment, never the real checkout.
  const synthetic = await db.booking.create({ data: {
    customerId: userIds[0], vendorId: ids("vendor"), serviceId: ids("service"), staffId: ids("staff"), locationType: "spa",
    startsAt: new Date(`${day}T16:00:00+01:00`), endsAt: new Date(`${day}T17:00:00+01:00`), status: "awaiting_payment",
    basePriceKobo: 10000, surchargeKobo: 0, commissionBps: 1000, commissionKobo: 1000,
    customerTotalKobo: 10000, vendorPayableKobo: 9000, surchargeRecipient: "vendor", planCodeSnapshot: "FREE", idempotencyKey: ids("synthetic-key")
  } });
  const syntheticRef = ids("synthetic-payment");
  await db.payment.create({ data: { bookingId: synthetic.id, provider: "integration_fixture", purpose: "booking", amountKobo: 10000, currency: "NGN", status: "pending", reference: syntheticRef, idempotencyKey: syntheticRef } });
  async function webhook(amount) {
    const raw = JSON.stringify({ event: "charge.success", data: { reference: syntheticRef, id: "synthetic-provider", amount, currency: "NGN" } });
    const signature = crypto.createHmac("sha512", process.env.PAYSTACK_WEBHOOK_SECRET || process.env.PAYSTACK_SECRET_KEY).update(raw).digest("hex");
    return request("/api/payments/webhook", { method: "POST", body: raw, headers: { "x-paystack-signature": signature } });
  }
  assert.notEqual((await webhook(9999)).status, 200);
  assert.equal((await db.payment.findUnique({ where: { reference: syntheticRef } })).status, "pending");
  const deliveries = await Promise.all([webhook(10000), webhook(10000)]);
  assert(deliveries.every((r) => r.status === 200), "Duplicate webhook failed");
  assert.equal((await db.booking.findUnique({ where: { id: synthetic.id } })).status, "confirmed");
  assert.equal(await db.vendorEarning.count({ where: { bookingId: synthetic.id } }), 1);
  assert.equal(await db.bookingStatusEvent.count({ where: { bookingId: synthetic.id, toStatus: "confirmed" } }), 1);
  report("synthetic-signed-webhook-amount-check-and-concurrent-idempotency", { gatewayCharge: false });
  // Remove the synthetic financial records now; retain only the genuine checkout.
  await db.vendorEarning.deleteMany({ where: { bookingId: synthetic.id } });
  await db.payment.deleteMany({ where: { bookingId: synthetic.id } });
  await db.booking.delete({ where: { id: synthetic.id } });
  const manifest = { run, base, userIds, vendorId: ids("vendor"), categoryId: ids("category"), staffId: ids("staff"), bookingId, reference, checkoutUrl: init.data.authorizationUrl };
  await mkdir(".integration-tests", { recursive: true });
  await writeFile(`.integration-tests/${run}.json`, JSON.stringify(manifest, null, 2));
  retained = true;
  report("sandbox-checkout-ready", { checkoutUrl: init.data.authorizationUrl, manifest: `.integration-tests/${run}.json`, checksPassed: passed });
} catch (error) {
  process.exitCode = 1;
  console.log(JSON.stringify({ check: "integration-run", ok: false, error: error?.code || error?.name, detail: error instanceof assert.AssertionError ? error.message : "Inspect the app logs; credentials are omitted" }));
} finally {
  if (!retained) await cleanup().catch((e) => console.log(JSON.stringify({ check: "cleanup", ok: false, code: e.code || e.name, fixturePrefix: run })));
  await db.$disconnect();
}
